"""Generate far-jmp thunks for the overlay entries.

The recovered code calls overlay entries as `ovr_<name>(...)`, declared with an
empty parameter list because the decompiler could not recover their arguments.
Calling the target directly through a C prototype would be rejected ("Too few
parameters"), and a C forwarding function would have to know the argument list -
which is exactly what is missing.

The original solves this the same way: each overlay entry is an INT 3Fh stub that
jumps to the resident routine, leaving the caller's stack frame untouched.  So
each thunk here is

        _ovr_blitRaw proc far
            jmp _blitRaw
        _ovr_blitRaw endp

i.e. arguments pass straight through, and no prototype is applied.  The mapping
thunk -> target is recorded in src/decompiled/ovr_stubs.c as `<addr> -> <name>`.

usage: python scripts/gen_ovr_thunks.py [--apply]
"""
import io
import os
import re
import sys

apply = "--apply" in sys.argv
FUNC = "src/decompiled/st_functions.h"
OUT = "src/decompiled/ovr_thunks.asm"

decl = re.compile(r"^\s*[A-Za-z_][\w \*]*?\b(ovr_(\w+))\s*\([^;]*\)\s*;\s*$")
thunks = []
for line in io.open(FUNC, encoding="utf-8", errors="ignore"):
    m = decl.match(line)
    if m and (m.group(1), m.group(2)) not in thunks:
        thunks.append((m.group(1), m.group(2)))

print("overlay thunks:", len(thunks))

# Some thunks have a real recovered body (e.g. ovr_midGetSequenceStatus_entry in
# ovc11); emitting an assembly thunk for those would duplicate the symbol.
import glob
defined = set()
for path in glob.glob("src/decompiled/*.c"):
    txt = io.open(path, encoding="utf-8", errors="ignore").read()
    for m in re.finditer(r"^[A-Za-z_][\w \*]*?\b([A-Za-z_]\w*)\s*\([^;{}]*$",
                         txt, re.M):
        defined.add(m.group(1))
have_body = [(t, g) for t, g in thunks if t in defined]
thunks = [(t, g) for t, g in thunks if t not in defined]
print("thunks with a recovered body (not generated):", len(have_body))

# Turbo Assembler truncates identifiers at 31 characters, and so does Turbo C.
# Truncate identically instead of dropping the thunk, otherwise the caller's
# reference (itself truncated) stays undefined.
skipped = []
thunks = [(("_" + t)[:31], ("_" + g)[:31]) for t, g in thunks]
seen = {}
uniq = []
for t, g in thunks:
    if t == g:
        print("  WARNING: thunk symbol equals its target:", t)
        continue
    if t in seen:
        print("  note: %s collides with %s after truncation" % (t, seen[t]))
        continue
    seen[t] = g
    uniq.append((t, g))
thunks = uniq

out = [
    "; Overlay entry thunks.  Each ovr_<name> is a far jump to <name>, so the",
    "; caller's arguments pass through untouched (the original used INT 3Fh).",
    "; Generated by scripts/gen_ovr_thunks.py.",
]
# externals must be declared before the segment, otherwise TASM resolves the
# jump as near and TLINK reports a fixup overflow.
for thunk, target in thunks:
    out.append("    extrn %s:far" % target)
out += [
    "",
    "OVRT_TEXT segment byte public 'CODE'",
    "    assume cs:OVRT_TEXT",
    "",
]
for thunk, target in thunks:
    out.append("    public %s" % thunk)
    out.append("%s proc far" % thunk)
    out.append("    jmp %s" % target)
    out.append("%s endp" % thunk)
    out.append("")
out += ["OVRT_TEXT ends", "    end", ""]

if apply:
    io.open(OUT, "w", encoding="ascii", newline="").write("\r\n".join(out))
print("mode:", "APPLY" if apply else "dry run")
