"""Generate far-jmp thunks for the overlay entries.

The recovered code calls overlay entries as `ovr_<name>(...)`, declared with an
empty parameter list because the decompiler could not recover their arguments.
Calling the target directly through a C prototype would be rejected ("Too few
parameters"), and a C forwarding function would have to know the argument list -
which is exactly what is missing.

The original solves this the same way: each overlay entry is an INT 3Fh stub that
jumps to the resident routine, leaving the caller's stack frame untouched.  So
each thunk here is

        _ovr_blitRaw proc far
            jmp _blitRaw
        _ovr_blitRaw endp

i.e. arguments pass straight through, and no prototype is applied.  The mapping
thunk -> target is recorded in src/decompiled/ovr_stubs.c as `<addr> -> <name>`.

usage: python scripts/gen_ovr_thunks.py [--apply]
"""
import io
import os
import re
import sys

apply = "--apply" in sys.argv
FUNC = "src/decompiled/st_functions.h"
OUT = "src/decompiled/ovr_thunks.asm"

decl = re.compile(r"^\s*[A-Za-z_][\w \*]*?\b(ovr_(\w+))\s*\([^;]*\)\s*;\s*$")
thunks = []
for line in io.open(FUNC, encoding="utf-8", errors="ignore"):
    m = decl.match(line)
    if m and (m.group(1), m.group(2)) not in thunks:
        thunks.append((m.group(1), m.group(2)))

print("overlay thunks:", len(thunks))

# Some thunks have a real recovered body (e.g. ovr_midGetSequenceStatus_entry in
# ovc11); emitting an assembly thunk for those would duplicate the symbol.
import glob
defined = set()
for path in glob.glob("src/decompiled/*.c"):
    txt = io.open(path, encoding="utf-8", errors="ignore").read()
    for m in re.finditer(r"^[A-Za-z_][\w \*]*?\b([A-Za-z_]\w*)\s*\([^;{}]*$",
                         txt, re.M):
        defined.add(m.group(1))
have_body = [(t, g) for t, g in thunks if t in defined]
thunks = [(t, g) for t, g in thunks if t not in defined]
print("thunks with a recovered body (not generated):", len(have_body))

# Turbo C keeps 31 significant characters of an identifier and then prefixes the
# underscore, so a 34-character C name becomes a 32-character external:
#
#     ovr_ovc28_usesBDADailyTimeCounter  ->  _ovr_ovc28_usesBDADailyTimeCounte
#     ovr_attact_textAbnormalProgramTermination -> _ovr_attact_textAbnormalProgramTe
#
# (read out of the caller's own object file).  The thunk must therefore be named
# "_" + name[:31]; TASM and TLINK both accept the result.  Truncating the symbol
# to 31 instead leaves it one character short and the call stays undefined.
# Two spellings of the same entry show up in the objects: the full name, and the
# 32-character form that Turbo C keeps when the name is longer than that
# (read out of the callers' object files: o16 references
#  ovr_ovr_miceButton0PressStates_e, o02 references the full name of others).
# Export a thunk under BOTH spellings so either caller resolves.  A spelling is
# claimed once; two different targets that truncate to the same symbol cannot both
# be served and are reported.
# Turbo C keeps 32 significant characters, so a long target is referenced
# truncated; the thunk must name it the same way.
base = [("_" + t[:32], "_" + g[:32]) for t, g in thunks]
seen = {}
uniq = []
for t, g in base:
    variants = [t]
    # Measured with tmp/probe_identlen.py: Turbo C keeps 32 significant
    # characters of an identifier (33..39 all collapse to 32), then the assembler
    # adds the leading underscore.
    if len(t) > 33:
        variants.append("_" + t[1:33])
    for v in variants:
        if v == g:
            print("  WARNING: thunk symbol equals its target:", v)
            continue
        if v in seen:
            if seen[v] != g:
                print("  note: %s is claimed by %s and %s" % (v, seen[v], g))
            continue
        seen[v] = g
        uniq.append((v, g))
thunks = uniq

out = [
    "; Overlay entry thunks.  Each ovr_<name> is a far jump to <name>, so the",
    "; caller's arguments pass through untouched (the original used INT 3Fh).",
    "; Generated by scripts/gen_ovr_thunks.py.",
]
# externals must be declared before the segment, otherwise TASM resolves the
# jump as near and TLINK reports a fixup overflow.
for thunk, target in thunks:
    out.append("    extrn %s:far" % target)
out += [
    "",
    "OVRT_TEXT segment byte public 'CODE'",
    "    assume cs:OVRT_TEXT",
    "",
]
for thunk, target in thunks:
    out.append("    public %s" % thunk)
    out.append("%s proc far" % thunk)
    out.append("    jmp %s" % target)
    out.append("%s endp" % thunk)
    out.append("")
# F_FTOL@ is the compiler's far "float to long" runtime helper.  Its name contains
# '@', which is not a C identifier, so it can only be provided from assembly: return
# 0 in DX:AX.  GUESS: the conversion is not needed by the data path we exercise.
out += [
    "    public F_FTOL@",
    "F_FTOL@ proc far",
    "    xor ax,ax",
    "    cwd",
    "    ret",
    "F_FTOL@ endp",
    "",
]
# Borland's 80-bit float I/O helpers have assembler names without the C underscore
# (FIDRQQ/FIWRQQ), so they cannot be defined in C.  GUESS: return 0 in DX:AX; the
# float scanner/printer then formats 0 instead of the value.
for _fp in ("FIDRQQ", "FIWRQQ"):
    out += [
        "    public %s" % _fp,
        "%s proc far" % _fp,
        "    xor ax,ax",
        "    cwd",
        "    ret",
        "%s endp" % _fp,
        "",
    ]

out += ["OVRT_TEXT ends", "    end", ""]

if apply:
    io.open(OUT, "w", encoding="ascii", newline="").write("\r\n".join(out))
print("mode:", "APPLY" if apply else "dry run")
