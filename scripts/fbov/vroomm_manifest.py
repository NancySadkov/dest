#!/usr/bin/env python3
"""Build the accepted-function manifest from a verifier log.

The verifier prints `=== ov_XXXX (seg) ===` followed by `PASS f_...` lines.
This tool parses such a log and merges the results into
`doc/vroomm_accepted.md`, keeping earlier entries for modules the log does
not cover (for example, modules whose harness failed to link).

Usage:
  python scripts/fbov/vroomm_manifest.py --log tmp/verify_all.log
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "doc", "vroomm_accepted.md")
ROW = re.compile(r"^\| `ov_([0-9a-f]{4})` \| (.*?) \|$")


def read_existing():
    if not os.path.exists(OUT):
        return {}
    rows = {}
    for line in open(OUT, encoding="ascii"):
        m = ROW.match(line.rstrip("\n"))
        if m:
            rows[int(m.group(1), 16)] = m.group(2)
    return rows


def parse_log(path):
    rows = {}
    cur = None
    for line in open(path, encoding="ascii", errors="replace"):
        m = re.match(r"=== ov_(\w+) \((\w+)\) ===", line)
        if m:
            cur = int(m.group(2), 16)
            rows.setdefault(cur, [])
            continue
        p = re.match(r"\s+PASS f_[0-9a-f]+_([0-9a-f]+) ofs=([0-9A-F]+) size=(\d+)", line)
        if p and cur is not None:
            rows[cur].append((int(p.group(1), 16), p.group(1).lower(), int(p.group(3))))
    return rows


def format_row(seg, items):
    items = sorted(set(items))
    parts = ["`%s`(%d)" % (name, size) for _, name, size in items]
    return "%d: %s" % (len(items), " ".join(parts))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", required=True)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()

    rows = {}
    for seg, cell in read_existing().items():
        items = []
        for name, size in re.findall(r"`([0-9a-f]+)`\((\d+)\)", cell):
            items.append((int(name, 16), name, int(size)))
        rows[seg] = items

    for seg, items in parse_log(a.log).items():
        rows.setdefault(seg, [])
        known = {(n, s) for _, n, s in rows[seg]}
        for item in items:
            if (item[1], item[2]) not in known:
                rows[seg].append(item)

    lines = [
        "# Accepted VROOMM functions",
        "",
        "Generated by the verifier sweep.  Each entry is `offset(size)`; every",
        "function matches the original bytes except call/jump operands.",
        "",
        "| Module | Accepted |",
        "|---|---|",
    ]
    total = 0
    for seg in sorted(rows):
        lines.append("| `ov_%04x` | %s |" % (seg, format_row(seg, rows[seg])))
        total += len(rows[seg])
    open(a.out, "w", encoding="ascii", newline="").write("\n".join(lines) + "\n")
    print("modules %d, functions %d, wrote %s" % (len(rows), total, a.out))


if __name__ == "__main__":
    main()
