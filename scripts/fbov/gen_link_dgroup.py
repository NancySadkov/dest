#!/usr/bin/env python3
"""Generate the link-time DGROUP object source.

Turbo Link reserves the first 8 bytes of DGROUP for the C0 startup data
(`__DATA`).  The recovered `dgroup.c` reproduces the *whole* original DGROUP,
including those 8 bytes, so linking it with compiler-generated objects shifts
every symbol by 8.

This generator emits a TASM source containing the original bytes from offset 8
onwards, with every symbol label relocated by -8.  TLINK's reserved 8 bytes
then put every symbol back at its original offset, so compiled references match
the original EXE bytes while the authoritative `dgroup.c` stays untouched.

Outputs:
  tmp/dglink/dgroup_link.asm
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tmp", "dglink")
HDR = 0
SIZE = 0x949A


def load_bytes():
    obj = os.path.join(ROOT, "tmp", "dgbuild", "DGROUP.OBJ")
    if os.path.exists(obj):
        sys.path.insert(0, os.path.join(ROOT, "scripts", "fbov"))
        from byte_match import parse_omf
        segdata, _ = parse_omf(obj)
        for data in segdata.values():
            if len(data) == SIZE:
                return bytes(data)
    exe = open(os.path.join(ROOT, "game", "STRONG.EXE"), "rb").read()
    return exe[0x15F00:0x15F00 + SIZE]


def load_symbols():
    """Extract raw PUBDEF names from the verified DGROUP.OBJ.

    dgroup_map.csv omits some gap arrays; the object is authoritative.
    Names are kept exactly as OMF stores them (C names with the leading _).
    """
    obj = os.path.join(ROOT, "tmp", "dgbuild", "DGROUP.OBJ")
    d = open(obj, "rb").read()
    i = 0
    syms = {}
    while i + 3 <= len(d):
        t = d[i]
        ln = d[i + 1] | (d[i + 2] << 8)
        pl = d[i + 3:i + 3 + ln]
        i += 3 + ln
        if t == 0x90:  # PUBDEF16
            j = 2
            while j < len(pl) - 1:
                n = pl[j]
                name = pl[j + 1:j + 1 + n].decode("ascii", "replace")
                j += 1 + n
                off = pl[j] | (pl[j + 1] << 8)
                j += 2
                ti = pl[j]
                j += 2 if ti & 0x80 else 1
                syms[name] = off
        elif t == 0x8A:
            break
    return syms


def main():
    os.makedirs(OUT, exist_ok=True)
    data = load_bytes()
    if len(data) != SIZE:
        raise SystemExit("DGROUP size mismatch: %d" % len(data))

    syms = sorted((off, name) for name, off in load_symbols().items()
                  if off >= HDR and name != "__DATA")


    lines = [
        "; generated by scripts/fbov/gen_link_dgroup.py -- do not edit",
        "DGROUP GROUP _DATA",
        "_DATA SEGMENT WORD PUBLIC 'DATA'",
    ]
    pos = HDR
    for off, name in syms:
        if off < pos:
            continue
        if off > pos:
            chunk = data[pos:off]
            for i in range(0, len(chunk), 16):
                lines.append("db " + ",".join("0%02Xh" % b for b in chunk[i:i + 16]))
            pos = off
        lab = name
        lines.append("PUBLIC " + lab)
        lines.append(lab + " LABEL BYTE")
    if pos < SIZE:
        chunk = data[pos:SIZE]
        for i in range(0, len(chunk), 16):
            lines.append("db " + ",".join("0%02Xh" % b for b in chunk[i:i + 16]))
    lines.append("_DATA ENDS")
    lines.append("END")
    path = os.path.join(OUT, "dglink.asm")
    open(path, "w", newline="\r\n").write("\n".join(lines) + "\n")
    print("wrote", path, "symbols", len(syms))


if __name__ == "__main__":
    main()
