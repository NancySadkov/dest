#!/usr/bin/env python3
"""Generate flat-build support segments from the original load module.

Creates tmp/flat/origsegs.asm containing:
  * copies of the original runtime CODE segments (0x1000, 0x138E, 0x13AA, 0x1403)
  * copies of every original static DATA segment except DGROUP (0x2410)
  * trampoline segments for the Borland overlay headers, each entry a
    far jump to the recovered C function
Also writes tmp/flat/segmap.json mapping original static segments to the
generated segment names and their content shifts.
"""
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MAN = os.path.join(ROOT, "doc", "fbov_manifest.json")
EXE = os.path.join(ROOT, "game", "STRONG.EXE")
OUT = os.path.join(ROOT, "tmp", "flat")
LOAD = 0x1E00
STATIC_BASE = 0x1000

m = json.load(open(MAN))
exe = open(EXE, "rb").read()

# ---- decide which static segments to copy -------------------------------
all_statics = set()
for s in m["segments"]:
    all_statics.add(s["static_seg"])
for ov in m["overlays"]:
    all_statics.add(ov["header_static_seg"])
    all_statics.add(ov["code_seg"])
all_statics = sorted(all_statics)


def next_static(static):
    for a in all_statics:
        if a > static:
            return a
    return static + 0x100


data = {}
for s in m["segments"]:
    if s["class"] != "DATA" or s["is_overlay"]:
        continue
    static = s["static_seg"]
    if static == 0x2410:            # DGROUP is provided by dglink.asm
        continue
    if static >= 0x2CA0:            # linker marker / stack segments
        continue
    if 0 < s["maxoff"] < 0xFF00:
        size = s["maxoff"]
    else:
        size = (next_static(static) - static) * 16
    if size <= 0:
        continue
    data[static] = max(data.get(static, 0), size)

code_statics = [0x1000, 0x138E, 0x13AA, 0x1403]

# symbols needed from the genuine runtime segments
import re
syms_by_seg = {0x1000: {}, 0x1403: {}}
for p in [os.path.join(OUT, "main.c")] + [
        os.path.join(OUT, f) for f in os.listdir(OUT)
        if f.startswith("ov_") and f.endswith(".c")]:
    src = open(p, encoding="ascii").read()
    for mm in re.finditer(r"\b(f_1000_([0-9a-f]{4}))\b", src):
        syms_by_seg[0x1000].setdefault(int(mm.group(2), 16), []).append(mm.group(1))
    for mm in re.finditer(r"\b(f_1403_([0-9a-f]{4}))\b", src):
        syms_by_seg[0x1403].setdefault(int(mm.group(2), 16), []).append(mm.group(1))
    for mm in re.finditer(r"\b(f_0000_2747)\b", src):
        syms_by_seg[0x1000].setdefault(0x2747, []).append(mm.group(1))
# every label maps to a list of aliases
for _s in syms_by_seg:
    for _k, _v in list(syms_by_seg[_s].items()):
        if isinstance(_v, str):
            syms_by_seg[_s][_k] = [_v]
syms_by_seg[0x1000].setdefault(0, []).append("ORIGSTART")
syms_by_seg[0x1000].setdefault(0x2747, [])
if "f_0000_2747" not in syms_by_seg[0x1000][0x2747]:
    syms_by_seg[0x1000][0x2747].append("f_0000_2747")

segmap = {"data": {}, "code": {}, "headers": {}}
lines = ["; generated by tmp/mk_origsegs.py -- do not edit"]
emit = lines.append


def emit_bytes(seg, data_bytes, labels=None):
    labels = labels or {}
    emit("%s SEGMENT PARA PUBLIC 'CODE'" % seg)
    i = 0
    n = len(data_bytes)
    while i < n:
        if i in labels:
            for name in labels[i]:
                emit("PUBLIC _%s" % name)
                emit("_%s LABEL FAR" % name)
        j = min(i + 16, n)
        # stop early if a label starts inside this chunk
        for k in range(i + 1, j):
            if k in labels:
                j = k
                break
        emit("db " + ",".join("0%02Xh" % b for b in data_bytes[i:j]))
        i = j
    if n in labels:
        for name in labels[n]:
            emit("PUBLIC _%s" % name)
            emit("_%s LABEL FAR" % name)
    emit("%s ENDS" % seg)
    emit("")


def seg_bytes(static, size):
    off = LOAD + (static - STATIC_BASE) * 16
    return exe[off:off + size]


for static in code_statics:
    size = None
    for s in m["segments"]:
        if s["static_seg"] == static:
            size = s["maxoff"]
            break
    if not size:
        continue
    name = "C%04X" % static
    segmap["code"][static] = {"seg": name, "shift": 0}
    labels = syms_by_seg.get(static, {})
    labels = {k: v for k, v in labels.items() if k < size}
    emit_bytes(name, seg_bytes(static, size), labels)

for static, size in sorted(data.items()):
    name = "D%04X" % static
    segmap["data"][static] = {"seg": name, "shift": 0}
    emit("%s SEGMENT PARA PUBLIC 'FARDATA'" % name)
    b = seg_bytes(static, size)
    for i in range(0, len(b), 16):
        emit("db " + ",".join("0%02Xh" % x for x in b[i:i + 16]))
    emit("%s ENDS" % name)
    emit("")

# ---- scratch segment for original marker targets ------------------------
emit("DZERO SEGMENT PARA PUBLIC 'DATA'")
emit("db 64 dup(0)")
emit("DZERO ENDS")
emit("")
segmap["zero"] = "DZERO"

# ---- overlay header trampolines -----------------------------------------
for ov in m["overlays"]:
    static = ov["header_static_seg"]
    name = "H%04X" % static
    segmap["headers"][static] = {"seg": name,
                                 "raw_header": ov["header_seg"],
                                 "code_seg": ov["code_seg"]}
    entries = []
    emit("%s SEGMENT PARA PUBLIC 'CODE'" % name)
    prefix = seg_bytes(static, 0x20)
    cur = 0
    if prefix:
        emit("db " + ",".join("0%02Xh" % b for b in prefix))
        cur = len(prefix)
    for t in sorted(ov.get("trampolines") or [], key=lambda x: x["header_off"]):
        off = t["header_off"]
        if off < cur:
            continue
        if off > cur:
            emit("db " + ",".join("00h" for _ in range(off - cur)))
            cur = off
        emit("db 0EAh,000h,000h,000h,000h")
        entries.append({"off": off, "code": ov["code_seg"],
                        "target": t["target_ofs"]})
        cur += 5
    emit("%s ENDS" % name)
    emit("")
    segmap["headers"][static]["entries"] = entries

open(os.path.join(OUT, "origsegs.asm"), "w", encoding="ascii",
     newline="").write("\r\n".join(lines) + "\r\nEND _ORIGSTART\r\n")
json.dump(segmap, open(os.path.join(OUT, "segmap.json"), "w"), indent=1)
print("wrote origsegs.asm: %d code segs, %d data segs, %d headers, %d labels"
      % (len(segmap["code"]), len(segmap["data"]), len(segmap["headers"]),
         sum(len(v) for v in syms_by_seg.values())))
