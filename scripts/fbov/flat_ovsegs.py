#!/usr/bin/env python3
"""Generate per-overlay flat-build assembly segments (one file each)."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'tmp', 'flat')
OSEG = os.path.join(OUT, 'ovs')
os.makedirs(OSEG, exist_ok=True)

m = json.load(open(os.path.join(ROOT, 'doc', 'fbov_manifest.json')))
exe = open(os.path.join(ROOT, 'game', 'STRONG.EXE'), 'rb').read()

objs = []
for ov in m['overlays']:
    seg = 'OV_%04X_TEXT' % ov['code_seg']
    code = exe[ov['code_file_offset']:ov['code_file_offset'] + ov['codesz']]
    labels = {}
    for t in (ov.get('trampolines') or []):
        name = 'f_%04x_%04x' % (ov['header_seg'], t['header_off'])
        labels.setdefault(t['target_ofs'], []).append(name)
    lines = ['; generated by tmp/mk_ovsegs2.py -- do not edit',
             '%s SEGMENT PARA PUBLIC \'CODE\'' % seg]
    i = 0
    n = len(code)
    while i < n:
        if i in labels:
            for name in labels[i]:
                lines.append('PUBLIC _%s' % name)
                lines.append('_%s LABEL FAR' % name)
        j = min(i + 32, n)
        for k in range(i + 1, j):
            if k in labels:
                j = k
                break
        lines.append('db ' + ','.join('0%02Xh' % b for b in code[i:j]))
        i = j
    if n in labels:
        for name in labels[n]:
            lines.append('PUBLIC _%s' % name)
            lines.append('_%s LABEL FAR' % name)
    lines.append('%s ENDS' % seg)
    lines.append('END')
    fn = 'ov_%04x.asm' % ov['code_seg']
    open(os.path.join(OSEG, fn), 'w', encoding='ascii', newline='').write('\r\n'.join(lines) + '\r\n')
    objs.append('ovs\\' + fn[:-4] + '.obj')

open(os.path.join(OUT, 'ovlist.txt'), 'w').write('\n'.join(objs) + '\n')
print('wrote', len(objs), 'overlay asm files')
