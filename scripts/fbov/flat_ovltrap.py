#!/usr/bin/env python3
"""Generate the resident overlay loader used by the flat development build.

The loader installs INT 3F, keeps OVL.BIN's overlay blobs on disk, loads the
requested overlay into a freshly allocated DOS block, applies the original
FBOV segment fixups, and far-jumps into it.  A return trampoline frees the
block again when the overlay function returns, so callers keep their own
overlay resident across nested calls.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'tmp', 'flat')

TEXT = r'''; generated by tmp/mk_ovltrap.py -- do not edit
OVLTRAP_TEXT SEGMENT PARA PUBLIC 'CODE'
    ASSUME cs:OVLTRAP_TEXT, ds:OVLTRAP_TEXT, es:nothing, ss:nothing

    PUBLIC _ovl_init, _ovl_handler, _ovl_tramp
    PUBLIC _ovl_codesz, _ovl_fixcnt
    PUBLIC _ovl_codeoff_lo, _ovl_codeoff_hi
    PUBLIC _ovl_fixoff_lo, _ovl_fixoff_hi, _ovl_slot_para, _ovl_dbg, _ovl_calls, _ovl_rets

; ---------------------------------------------------------------- init ----
_ovl_init PROC FAR
    push ds
    push ax
    push dx
    push bx
    mov ax, ds
    mov cs:load_base, ax
    mov ax, cs
    mov ds, ax
    mov dx, OFFSET _ovl_handler
    mov ax, 253Fh
    int 21h
    mov cs:_ovl_dbg, 1
    mov dx, OFFSET ovl_name
    mov ax, 3D00h
    int 21h
    jc init_fail
    mov cs:ovl_handle, ax
    mov cs:_ovl_dbg, 2
    jmp init_done
init_fail:
    mov cs:ovl_handle, 0FFFFh
init_done:
    pop bx
    pop dx
    pop ax
    pop ds
    retf
_ovl_init ENDP

; ------------------------------------------------------------- handler ----
; Entered through INT 3F.  Header entry bytes are CD 3F <ov> <ofs:lo> <ofs:hi>.
_ovl_handler PROC FAR
    inc word ptr cs:_ovl_calls
    mov cs:saved_ss, ss
    mov cs:saved_sp, sp
    mov cs:save_ax, ax
    cld
    mov ax, cs
    mov ss, ax
    mov sp, OFFSET trap_top
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    push ds
    push es
    push cs
    pop ds

    ; read the inline target descriptor
    mov ax, cs:saved_ss
    mov es, ax
    mov si, cs:saved_sp
    mov bx, es:[si]              ; IP just after INT 3F
    mov ax, es:[si+2]            ; header segment
    mov es, ax
    xor ax, ax
    mov al, es:[bx]              ; overlay id
    mov cs:cur_ov, ax
    mov dx, es:[bx+1]            ; target offset
    mov cs:cur_ofs, dx

    ; remember the caller's return address
    mov ax, cs:saved_ss
    mov es, ax
    mov si, cs:saved_sp
    mov ax, es:[si+6]
    mov cs:cur_ret_ip, ax
    mov ax, es:[si+8]
    mov cs:cur_ret_cs, ax
    mov ax, es:[si+4]
    mov cs:save_flags, ax

    ; allocate a slot from the resident pool
    mov bx, 7
find_slot:
    cmp byte ptr cs:slot_use[bx], 0
    je  got_slot
    dec bx
    jns find_slot
    mov cs:_ovl_dbg, 3
    jmp ovl_fail
got_slot:
    mov byte ptr cs:slot_use[bx], 1
    mov cs:cur_slotidx, bx
    shl bx, 1
    mov ax, cs:_ovl_slot_para[bx]
    add ax, cs:load_base
    mov cs:cur_slot, ax
    ; code size
    mov bx, cs:cur_ov
    shl bx, 1
    mov ax, cs:_ovl_codesz[bx]
    mov cs:cur_size, ax

    ; seek to the code blob and read it into the block
    mov bx, cs:cur_ov
    shl bx, 1
    mov dx, cs:_ovl_codeoff_lo[bx]
    mov cx, cs:_ovl_codeoff_hi[bx]
    mov ax, 4200h
    mov bx, cs:ovl_handle
    int 21h
    push ds
    mov ax, cs:cur_slot
    mov ds, ax
    xor dx, dx
    mov cx, cs:cur_size
    mov bx, cs:ovl_handle
    mov ah, 3Fh
    int 21h
    pop ds

    ; read and apply the fixup list
    mov bx, cs:cur_ov
    shl bx, 1
    mov ax, cs:_ovl_fixcnt[bx]
    mov cs:cur_fixcnt, ax
    test ax, ax
    jnz do_fixups
    jmp fix_done
do_fixups:
    mov dx, cs:_ovl_fixoff_lo[bx]
    mov cx, cs:_ovl_fixoff_hi[bx]
    mov ax, 4200h
    mov bx, cs:ovl_handle
    int 21h
    mov cx, cs:cur_fixcnt
    shl cx, 1
    shl cx, 1
    mov dx, OFFSET fixbuf
    mov bx, cs:ovl_handle
    mov ah, 3Fh
    int 21h
    mov si, OFFSET fixbuf
    mov cx, cs:cur_fixcnt
fix_loop:
    mov di, cs:[si]
    mov ax, cs:[si+2]
    add ax, cs:load_base
    push ds
    mov bx, cs:cur_slot
    mov ds, bx
    mov [di], ax
    pop ds
    add si, 4
    loop fix_loop
fix_done:

    ; push a call record
    mov bx, cs:depth
    cmp bx, 32
    jb  rec_ok
    mov cs:_ovl_dbg, 6
    jmp ovl_fail
rec_ok:
    mov ax, bx
    mov cx, 6
    mul cx
    mov si, ax
    mov ax, cs:cur_ret_ip
    mov word ptr cs:recs[si], ax
    mov ax, cs:cur_ret_cs
    mov word ptr cs:recs[si+2], ax
    mov ax, cs:cur_slotidx
    mov word ptr cs:recs[si+4], ax
    inc word ptr cs:depth

    ; replace the caller's return address with the trampoline
    mov ax, cs:saved_ss
    mov es, ax
    mov si, cs:saved_sp
    mov word ptr es:[si+6], OFFSET _ovl_tramp
    mov ax, cs
    mov word ptr es:[si+8], ax

    ; far jump target, preserving all caller registers
    mov ax, cs:cur_ofs
    mov cs:jump_ip, ax
    mov ax, cs:cur_slot
    mov cs:jump_cs, ax
    pop es
    pop ds
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    mov ss, cs:saved_ss
    mov sp, cs:saved_sp
    add sp, 6
    push word ptr cs:save_flags
    popf
    mov ax, cs:save_ax
    jmp dword ptr cs:[jump_ptr]

ovl_fail:
    cli
    hlt
    jmp ovl_fail
_ovl_handler ENDP

; ---------------------------------------------------------- trampoline ----
; The target function returns here.  Free its block and resume the caller.
_ovl_tramp PROC FAR
    inc word ptr cs:_ovl_rets
    mov cs:saved_ss, ss
    mov cs:saved_sp, sp
    mov cs:save_ax, ax
    pushf
    pop word ptr cs:save_flags
    cld
    mov ax, cs
    mov ss, ax
    mov sp, OFFSET trap_top
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    push ds
    push es
    push cs
    pop ds

    dec word ptr cs:depth
    mov bx, cs:depth
    mov ax, bx
    mov cx, 6
    mul cx
    mov si, ax
    mov ax, word ptr cs:recs[si]
    mov cs:cur_ret_ip, ax
    mov ax, word ptr cs:recs[si+2]
    mov cs:cur_ret_cs, ax
    mov bx, word ptr cs:recs[si+4]
    mov byte ptr cs:slot_use[bx], 0
    mov ax, cs:cur_ret_ip
    mov cs:jump_ip, ax
    mov ax, cs:cur_ret_cs
    mov cs:jump_cs, ax
    pop es
    pop ds
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    mov ss, cs:saved_ss
    mov sp, cs:saved_sp
    push word ptr cs:save_flags
    popf
    mov ax, cs:save_ax
    jmp dword ptr cs:[jump_ptr]
_ovl_tramp ENDP

; ------------------------------------------------------------- tables ----
ALIGN 2
_ovl_codesz      LABEL WORD
    dw 51 dup(0)
_ovl_fixcnt      LABEL WORD
    dw 51 dup(0)
_ovl_codeoff_lo  LABEL WORD
    dw 51 dup(0)
_ovl_codeoff_hi  LABEL WORD
    dw 51 dup(0)
_ovl_fixoff_lo   LABEL WORD
    dw 51 dup(0)
_ovl_fixoff_hi   LABEL WORD
    dw 51 dup(0)
_ovl_slot_para   LABEL WORD
    dw 8 dup(0)
_ovl_dbg         LABEL WORD
    dw 0
_ovl_calls       LABEL WORD
    dw 0
_ovl_rets        LABEL WORD
    dw 0

load_base   dw 0
ovl_handle  dw 0FFFFh
saved_ss    dw 0
saved_sp    dw 0
save_ax     dw 0
save_flags  dw 0
cur_ov      dw 0
cur_ofs     dw 0
cur_slot    dw 0
cur_size    dw 0
cur_fixcnt  dw 0
cur_ret_ip  dw 0
cur_ret_cs  dw 0
depth       dw 0
jump_ptr    LABEL DWORD
jump_ip     dw 0
jump_cs     dw 0
recs        db 32*6 dup(0)
slot_use    db 8 dup(0)
cur_slotidx dw 0
fixbuf      db 1216*4 dup(0)
trap_stack  db 1024 dup(0)
trap_top    LABEL BYTE
ovl_name    db 'OVL.BIN',0

OVLTRAP_TEXT ENDS
END
'''

open(os.path.join(OUT, 'ovltrap.asm'), 'w', encoding='ascii',
     newline='').write(TEXT.replace('\n', '\r\n'))
print('wrote ovltrap.asm')
