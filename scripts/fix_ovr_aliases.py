"""Route overlay thunks straight to their target function.

The recovered code calls overlay entries as `ovr_<name>(...)`.  In this rebuild
there are no overlays - every module is linked into the one image - so `ovr_<name>`
IS `<name>`.  ovr_stubs.c already records the pairing for every thunk
(`22a6:0043 -> blitRaw`), and the recovered header repeats it as
`undefined ovr_blitRaw();`.

This emits st_ovr.h with

    #define ovr_blitRaw blitRaw

for every thunk, and drops the `undefined ovr_*();` prototypes from
st_functions.h (they would otherwise be rewritten into conflicting declarations).

usage: python scripts/fix_ovr_aliases.py [--apply]
"""
import io
import os
import re
import sys

apply = "--apply" in sys.argv
FUNC = "src/decompiled/st_functions.h"
OUT = "src/decompiled/st_ovr.h"

lines = io.open(FUNC, encoding="utf-8", errors="ignore").read().split("\n")

decl = re.compile(r"^\s*[A-Za-z_][\w \*]*?\b(ovr_(\w+))\s*\([^;]*\)\s*;\s*$")
aliases = []
keep = []
for line in lines:
    m = decl.match(line)
    if m:
        aliases.append((m.group(1), m.group(2)))
        continue
    keep.append(line)

print("overlay thunks aliased:", len(aliases))
dupes = len(aliases) - len(set(a for a, _ in aliases))
print("duplicate declarations:", dupes)

out = ["/* Overlay thunk aliases: no overlays in this build, so ovr_X is X.",
       "   Generated by scripts/fix_ovr_aliases.py. */",
       "#ifndef ST_OVR_H", "#define ST_OVR_H", ""]
for thunk, target in aliases:
    out.append("#define %s %s" % (thunk, target))
out += ["", "#endif", ""]

if apply:
    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    io.open(FUNC, "w", encoding="utf-8", newline="\n").write("\n".join(keep))
print("mode:", "APPLY" if apply else "dry run")
